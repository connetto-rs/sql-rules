//! Keys the database generates, serial and identity alike, observed through
//! the public constrainer API.

use sql_rules::prelude::*;
use sqlparser::dialect::PostgreSqlDialect;

/// Rule name and message of every violation, failing on anything else.
fn findings(constrainer: &GenericConstrainer<ParserDB>, sql: &str) -> Vec<(String, String)> {
    constrainer
        .diagnostics(&ParserDB::parse::<PostgreSqlDialect>(sql).expect("schema parses"))
        .into_iter()
        .map(|error| match error {
            Error::Violation(violation) => (
                violation.rule().name.to_owned(),
                violation.message().to_owned(),
            ),
            other => panic!("unexpected failure: {other}"),
        })
        .collect()
}

#[test]
fn an_identity_primary_key_in_an_extension_table_is_a_surrogate() {
    let constrainer: GenericConstrainer<ParserDB> =
        NoSurrogatePrimaryKeyInExtension::default().into();
    for key in [
        "id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY",
        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "id serial PRIMARY KEY",
    ] {
        let raised = findings(
            &constrainer,
            &format!(
                "CREATE TABLE roots (id INT PRIMARY KEY);
                 CREATE TABLE children ({key}, FOREIGN KEY (id) REFERENCES roots (id));"
            ),
        );
        assert_eq!(raised.len(), 1, "{key}");
        assert!(
            raised[0].1.contains("is generated"),
            "{key}: {}",
            raised[0].1
        );
    }
}

#[test]
fn a_computed_primary_key_in_an_extension_table_is_not_a_surrogate() {
    let constrainer: GenericConstrainer<ParserDB> =
        NoSurrogatePrimaryKeyInExtension::default().into();
    assert_eq!(
        findings(
            &constrainer,
            "CREATE TABLE roots (id INT PRIMARY KEY);
             CREATE TABLE children (
                 id INT GENERATED ALWAYS AS (1) STORED PRIMARY KEY,
                 FOREIGN KEY (id) REFERENCES roots (id)
             );"
        ),
        []
    );
}

#[test]
fn identity_columns_on_both_sides_of_a_foreign_key_match_only_by_coincidence() {
    let constrainer: GenericConstrainer<ParserDB> = CompatibleForeignKey::default().into();
    let raised = findings(
        &constrainer,
        "CREATE TABLE parents (id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
         CREATE TABLE children (
             id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
             FOREIGN KEY (id) REFERENCES parents (id)
         );",
    );
    assert_eq!(raised.len(), 1);
    assert!(
        raised[0].1.contains("both generate their own values"),
        "{}",
        raised[0].1
    );
}
